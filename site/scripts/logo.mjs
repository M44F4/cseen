/*
 * Builds the logo for the site from the four master SVGs in src/brand (colour and one-colour, mark and full), which
 * scripts/mark.mjs draws:
 *   node scripts/logo.mjs
 * Writes src/brand/logo-sprite.ts (one <symbol> per logo, drawn once per page and reused with <use>) and
 * public/favicon.svg. The colour logo has two roles: A (the ink, black) and B (the accent, green). The page
 * decides which two colours they get, or switches to the one-colour logo, through --cn-logo-a, --cn-logo-b
 * and html[data-logo="mono"] (see src/theme.ts).
 */
import { readFileSync, writeFileSync } from 'node:fs';

const read = (n) => readFileSync(new URL(`../src/brand/${n}.svg`, import.meta.url), 'utf8');
const ROLE = { '#0B0B0B': 'lg-a', '#00A86B': 'lg-b' };

/** the shapes of a master svg, in painting order, each with its role class */
function shapes(svg, mono) {
  const out = [], fills = [];
  for (const line of svg.split('\n')) {
    if (/^\s*<g\b/.test(line)) { fills.push(/\sfill="(#[0-9A-Fa-f]{6})"/.exec(line)?.[1] ?? fills.at(-1) ?? null); continue; }
    if (/^\s*<\/g>/.test(line)) { fills.pop(); continue; }
    const own = /\sfill="(#[0-9A-Fa-f]{6})"/.exec(line)?.[1] ?? fills.at(-1);
    const cls = mono ? 'lg-m' : ROLE[own?.toUpperCase()];
    const d = /\sd="([^"]+)"/.exec(line)?.[1];
    if (/^\s*<path/.test(line)) { if (!cls) throw new Error(`unknown fill ${own}`); out.push(`<path class="${cls}" d="${d}"/>`); }
    else if (/^\s*<circle/.test(line)) { if (!cls) throw new Error(`unknown fill ${own}`); out.push(`<circle class="${cls}" cx="${/cx="([^"]+)"/.exec(line)[1]}" cy="${/cy="([^"]+)"/.exec(line)[1]}" r="${/\sr="([^"]+)"/.exec(line)[1]}"/>`); }
  }
  return out.join('');
}
const box = (svg) => /viewBox="([^"]+)"/.exec(svg)[1];

const logos = {};
for (const kind of ['mark', 'full']) {
  const c = read(`${kind}-color`), m = read(`${kind}-mono`);
  if (box(c) !== box(m)) throw new Error(`${kind}: colour and one-colour boxes differ`);
  logos[kind] = { box: box(c), symbol: `<symbol id="cn-logo-${kind}" viewBox="${box(c)}"><g class="lg-color">${shapes(c, false)}</g><g class="lg-mono">${shapes(m, true)}</g></symbol>` };
}
const body = `export const LOGO_BOX = ${JSON.stringify({ mark: logos.mark.box, full: logos.full.box })} as const;\nexport const LOGO_SPRITE = ${JSON.stringify(logos.mark.symbol + logos.full.symbol)};\n`;
writeFileSync(new URL('../src/brand/logo-sprite.ts', import.meta.url), `// Generated by scripts/logo.mjs from the master SVGs in this folder. Do not edit.\n${body}`);

// favicon: the mark alone. A tab can be light or dark, so it wears the light theme's pair by day and the dark theme's by night
const [x, y, w, h] = logos.mark.box.split(' ').map(Number), pad = 40, side = Math.max(w, h) + 2 * pad;
const fav = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${(x + w / 2 - side / 2).toFixed(2)} ${(y + h / 2 - side / 2).toFixed(2)} ${side.toFixed(2)} ${side.toFixed(2)}" role="img" aria-label="cseen"><title>cseen</title><style>.lg-a{fill:#0B0B0B}.lg-b{fill:#00A86B}@media (prefers-color-scheme:dark){.lg-a{fill:#F2F2F2}.lg-b{fill:#1FD493}}</style>${shapes(read('mark-color'), false)}</svg>\n`;
writeFileSync(new URL('../public/favicon.svg', import.meta.url), fav);
console.log(`wrote src/brand/logo-sprite.ts (${body.length} bytes) and public/favicon.svg (${fav.length} bytes)`);
